test("public parity keeps previously clean subjects and adds newly promoted obligations", async t =>
{
  const options = await fixture(t, {
    "trinity/core/A.js": 'export class A { Tick() {} }',
    "trinity/generated/core/B.js": 'export class B {}'
  }, Object.fromEntries(["A", "B"].map(blueClass => [`core/${blueClass}`, {blueClass,family:"core",nativeMethods:[{cppName:"Tick"}]}])));
  const root = path.dirname(options.sourceRoot);
  for (const directory of ["scripts/trinity", "src/trinity/dropped", "src/global/blue", "src/trinityal"])
    await fs.mkdir(path.join(root,directory),{recursive:true});
  await fs.writeFile(path.join(root,"package.json"),'{"type":"module"}');
  await fs.writeFile(path.join(root,"scripts/trinity-parity-baseline.json"),'{"findings":[]}');
  const auditUrl = new URL("../../scripts/trinity/audit_public_method_parity.js",import.meta.url);
  let script = await fs.readFile(auditUrl,"utf8");
  script = script.replace('from "@babel/parser"',`from ${JSON.stringify(import.meta.resolve("@babel/parser"))}`);
  script = script.replace('from "./carbon-decorators.js"',`from ${JSON.stringify(new URL("carbon-decorators.js",auditUrl).href)}`);
  const audit = path.join(root,"scripts/trinity/audit_public_method_parity.js");
  await fs.writeFile(audit,script);
  const initial = {skipped:[{className:"A",family:"core",reason:"hand-maintained source exists"}]};
  const summary = updateOwnershipSummary(initial,await readGeneratedOwnership(options));
  const summaryFile = path.join(root,"src/trinity/generated/summary.json");
  await fs.writeFile(summaryFile,JSON.stringify(summary));
  const run = () => spawnSync(process.execPath,[audit,"--schema-root",options.schemaRoot],{encoding:"utf8",windowsHide:true});
  assert.equal(run().status,0,"a previously clean class remains a subject without needing a baseline finding");
  await fs.writeFile(path.join(options.sourceRoot,"trinity/core/A.js"),'export class A {}');
  const broken = run();
  assert.equal(broken.status,1);
  assert.match(broken.stderr,/omitted A.Tick/);
  await fs.writeFile(path.join(options.sourceRoot,"trinity/core/A.js"),'export class A { Tick() {} }');
  await fs.rename(path.join(options.sourceRoot,"trinity/generated/core/B.js"),path.join(options.sourceRoot,"trinity/core/B.js"));
  await fs.writeFile(summaryFile,JSON.stringify(updateOwnershipSummary(summary,await readGeneratedOwnership(options))));
  const promoted = run();
  assert.equal(promoted.status,1);
  assert.match(promoted.stderr,/omitted B.Tick/);
});

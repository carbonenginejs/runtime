test('sprite texture edits notify native targets once after coalesced changed values',()=>{
  const texture=new Tr2Sprite2dTexture(),seen=[];
  assert.equal(CjsSchema.cast(texture,INotify),texture);
  texture.RegisterForChangeNotification({Sprite2dTextureChanged(changed){
    seen.push({changed,rotation:changed.rotation,translation:Array.from(changed.translation),useTransform:changed.useTransform});
  }});
  CjsSchema.setValues(texture,{rotation:0.75,translation:[2,3],useTransform:true});
  assert.deepEqual(seen,[{changed:texture,rotation:0.75,translation:[2,3],useTransform:true}]);
  CjsSchema.setValues(texture,{rotation:0.75,translation:[2,3],useTransform:true});
  assert.equal(seen.length,1,'equal values do not send a second notification');
  CjsSchema.setValues(texture,{name:'renamed'});assert.equal(seen.length,1,'name is not native NOTIFY');
});

test('duplicate registration and unregister follow native identity-set semantics',()=>{
  const texture=new Tr2Sprite2dTexture(),seen=[];
  const first={Sprite2dTextureChanged:changed=>seen.push(['first',changed])};
  const second={Sprite2dTextureChanged:changed=>seen.push(['second',changed])};
  texture.RegisterForChangeNotification(first);texture.RegisterForChangeNotification(first);texture.RegisterForChangeNotification(second);
  assert.equal(texture.OnModified('rotation'),true);
  assert.equal(seen.length,2);assert.ok(seen.every(entry=>entry[1]===texture));
  texture.UnregisterForChangeNotification(first);texture.UnregisterForChangeNotification(first);seen.length=0;
  texture.SetDirty();assert.deepEqual(seen,[['second',texture]]);
  texture.UnregisterForChangeNotification(second);texture.SetDirty();assert.equal(seen.length,1);
});

test('atlas callbacks and explicit changed-name arrays use the same listener path',()=>{
  const texture=new Tr2Sprite2dTexture(),seen=[];
  texture.RegisterForChangeNotification({Sprite2dTextureChanged:changed=>seen.push(changed)});
  texture.AtlasTextureChanged({});NotifyModified(texture,['rotation','scalingCenter']);
  assert.deepEqual(seen,[texture,texture]);
  texture.OnModified(null);assert.deepEqual(seen,[texture,texture,texture]);
});


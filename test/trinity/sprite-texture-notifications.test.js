function atlas(width=128,height=64) {
  const listeners=new Set();
  return {listeners,GetWidth:()=>width,GetHeight:()=>height,IsGood:()=>true,IsLoading:()=>false,
    RegisterForChangeNotification:target=>listeners.add(target),UnregisterForChangeNotification:target=>listeners.delete(target)};
}

test('sprite atlas replacement, cropping and Apply preserve the native callback order',()=>{
  const texture=new Tr2Sprite2dTexture(),first=atlas(),second=atlas(256,128),calls=[];
  assert.equal(texture.GetWidth(),0);assert.equal(texture.IsGood(),false);assert.equal(texture.IsLoading(),false);
  texture.SetAtlasTexture(first);assert.ok(first.listeners.has(texture));assert.equal(texture.GetAtlasTexture(),first);
  assert.equal(texture.GetHeight(),64);assert.equal(texture.IsGood(),true);
  const renderer={SetTexture:(...args)=>calls.push(['texture',...args]),SetTextureWindow:(...args)=>calls.push(['window',...args]),
    SetTextureTransform:(...args)=>calls.push(['transform',...args]),SetTileMode:(...args)=>calls.push(['tile',...args])};
  texture.Apply(renderer,2);assert.deepEqual(calls.map(c=>c[0]),['texture','transform','tile']);
  texture.srcWidth=128;texture.srcHeight=64;calls.length=0;texture.Apply(renderer,2);
  assert.deepEqual(calls.map(c=>c[0]),['texture','transform','tile'],'exact full rectangle needs no window');
  texture.srcX=3;calls.length=0;texture.Apply(renderer,2);assert.deepEqual(calls[1],['window',2,3,0,128,64]);
  assert.deepEqual(calls.map(c=>c[0]),['texture','window','transform','tile']);
  texture.SetAtlasTexture(second);assert.equal(first.listeners.size,0);assert.ok(second.listeners.has(texture));
  texture.Destroy();texture.Destroy();assert.equal(second.listeners.size,0);assert.equal(texture.GetAtlasTexture(),null);
});

test('repeat flags retain the native unshifted setter quirk while tiling preserves unrelated bits',()=>{
  const texture=new Tr2Sprite2dTexture();texture.tileX=true;texture.tileY=true;
  texture.repeatMode=1;assert.equal(texture.repeatMode,0,'native writes 1 as FORCEOPAQUE, not MIRROR');
  texture.repeatMode=2;assert.equal(texture.repeatMode,1);assert.equal(texture._settings,27);
  texture.tileX=false;assert.equal(texture.tileY,true);assert.equal(texture._settings,19);
  texture.repeatMode=4;assert.equal(texture.repeatMode,2);assert.equal(texture._settings,21);
});

test('centered texture matrices apply oriented nonuniform scaling before rotation and translation',()=>{
  const texture=new Tr2Sprite2dTexture();assert.equal(texture.GetTransform(),null);
  texture.useTransform=true;texture.scalingCenter.set([1,2]);texture.scale.set([2,3]);texture.scalingRotation=Math.PI/2;
  texture.rotationCenter.set([4,5]);texture.rotation=Math.PI/2;texture.translation.set([6,7]);
  const transform=texture.GetTransform(),expected=[0,3,0,0,-2,0,0,0,0,0,1,0,17,6,0,1];
  transform.forEach((value,index)=>assert.ok(Math.abs(value-expected[index])<1e-5,`${index}: ${value}`));
  assert.equal(texture.GetTransform(),transform,'native retained output identity');
  texture.translation[0]=8;assert.ok(Math.abs(texture.GetTransform()[12]-19)<1e-5);
  texture.useTransform=false;assert.equal(texture.GetTransform(),null);
});


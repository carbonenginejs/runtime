/** @param {number} d3d11Filter A `D3D11_FILTER` value. @returns {number} Carbon's `D3D11_DECODE_MIN_FILTER`. */
export function D3D11_DECODE_MIN_FILTER(d3d11Filter)
{
    return (d3d11Filter >> D3D11_MIN_FILTER_SHIFT) & D3D11_FILTER_TYPE_MASK;
}

/** @param {number} d3d11Filter A `D3D11_FILTER` value. @returns {number} Carbon's `D3D11_DECODE_MAG_FILTER`. */
export function D3D11_DECODE_MAG_FILTER(d3d11Filter)
{
    return (d3d11Filter >> D3D11_MAG_FILTER_SHIFT) & D3D11_FILTER_TYPE_MASK;
}

/** @param {number} d3d11Filter A `D3D11_FILTER` value. @returns {number} Carbon's `D3D11_DECODE_MIP_FILTER`. */
export function D3D11_DECODE_MIP_FILTER(d3d11Filter)
{
    return (d3d11Filter >> D3D11_MIP_FILTER_SHIFT) & D3D11_FILTER_TYPE_MASK;
}

/** @param {number} d3d11Filter A `D3D11_FILTER` value. @returns {number} Carbon's `D3D11_DECODE_FILTER_REDUCTION`. */
export function D3D11_DECODE_FILTER_REDUCTION(d3d11Filter)
{
    return (d3d11Filter >> D3D11_FILTER_REDUCTION_TYPE_SHIFT) & D3D11_FILTER_REDUCTION_TYPE_MASK;
}

/** @param {number} d3d11Filter A `D3D11_FILTER` value. @returns {boolean} Carbon's `D3D11_DECODE_IS_COMPARISON_FILTER`. */
export function D3D11_DECODE_IS_COMPARISON_FILTER(d3d11Filter)
{
    return D3D11_DECODE_FILTER_REDUCTION(d3d11Filter) === D3D11_FILTER_REDUCTION_TYPE.D3D11_FILTER_REDUCTION_TYPE_COMPARISON;
}

/** @param {number} d3d11Filter A `D3D11_FILTER` value. @returns {boolean} Carbon's `D3D11_DECODE_IS_ANISOTROPIC_FILTER`. */
export function D3D11_DECODE_IS_ANISOTROPIC_FILTER(d3d11Filter)
{
    const linear = D3D11_FILTER_TYPE.D3D11_FILTER_TYPE_LINEAR;
    return (d3d11Filter & D3D11_ANISOTROPIC_FILTERING_BIT) !== 0 &&
        D3D11_DECODE_MIN_FILTER(d3d11Filter) === linear &&
        D3D11_DECODE_MAG_FILTER(d3d11Filter) === linear &&
        D3D11_DECODE_MIP_FILTER(d3d11Filter) === linear;
}

